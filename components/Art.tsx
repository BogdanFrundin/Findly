/** Product picture: the store photo when the feed has one, otherwise an illustration. */
export function ProductImage({ p, tone, scale, floor = true, className = "reveal" }: { p: Product; tone?: string; scale?: number; floor?: boolean; className?: string }) {
  if (p.image) return <img src={p.image} alt={p.name} loading="lazy" className={className} />;
  return <Svg html={garmentSvg(p.shape, tone || p.tone, { scale: scale ?? 1, floor })} className={className} />;
}

export function Svg({ html, className }: { html: string; className?: string }) {
  // The markup is generated by lib/art.ts from fixed shapes, never from user input.
  const h = className ? html.replace("<svg ", `<svg class="${className}" `) : html;
  return <span style={{ display: "contents" }} dangerouslySetInnerHTML={{ __html: h }} />;
}
